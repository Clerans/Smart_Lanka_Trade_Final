-- Create AI_RECOMMENDATIONS Table (AI/ML Trading Engine)
CREATE TABLE AI_RECOMMENDATIONS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER,
    SYMBOL VARCHAR2(20) NOT NULL,
    TIMEFRAME VARCHAR2(10) DEFAULT '1h' NOT NULL,
    PRICE_USD NUMBER(18, 8) NOT NULL,
    PRICE_LKR NUMBER(18, 2) NOT NULL,
    RECOMMENDATION VARCHAR2(10) NOT NULL, -- 'BUY', 'HOLD', 'SELL'
    CONFIDENCE NUMBER(5, 2) NOT NULL,
    RISK_LEVEL VARCHAR2(10) NOT NULL, -- 'LOW', 'MEDIUM', 'HIGH'
    TREND VARCHAR2(10) NOT NULL, -- 'BULLISH', 'BEARISH', 'NEUTRAL'
    RSI NUMBER(8, 2),
    SMA20 NUMBER(18, 8),
    SMA50 NUMBER(18, 8),
    EMA20 NUMBER(18, 8),
    MACD NUMBER(18, 8),
    MACD_SIGNAL NUMBER(18, 8),
    MACD_HISTOGRAM NUMBER(18, 8),
    VOLATILITY NUMBER(10, 6),
    REASONS VARCHAR2(4000),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_AI_REC_USER FOREIGN KEY (USER_ID) REFERENCES SL_USERS(ID)
);

CREATE INDEX IDX_AI_REC_SYM ON AI_RECOMMENDATIONS(SYMBOL);
CREATE INDEX IDX_AI_REC_CREATED ON AI_RECOMMENDATIONS(CREATED_AT);

-- Create KYC_DOCUMENTS Table (OCR-Based Identity Verification)
CREATE TABLE KYC_DOCUMENTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    DOCUMENT_TYPE VARCHAR2(20) DEFAULT 'NIC' NOT NULL,
    DOCUMENT_NUMBER VARCHAR2(50),
    EXTRACTED_NAME VARCHAR2(200),
    EXTRACTED_DOB VARCHAR2(50),
    EXTRACTED_GENDER VARCHAR2(20),
    OCR_TEXT VARCHAR2(4000),
    OCR_CONFIDENCE NUMBER(5, 2),
    VERIFICATION_STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL, -- 'VERIFIED', 'PENDING', 'REJECTED'
    REJECTION_REASON VARCHAR2(500),
    DOCUMENT_PATH VARCHAR2(500),
    SUBMITTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    VERIFIED_AT TIMESTAMP,
    VERIFIED_BY NUMBER,
    CONSTRAINT FK_KYC_DOC_USER FOREIGN KEY (USER_ID) REFERENCES SL_USERS(ID)
);

CREATE INDEX IDX_KYC_USER ON KYC_DOCUMENTS(USER_ID);
CREATE INDEX IDX_KYC_STATUS ON KYC_DOCUMENTS(VERIFICATION_STATUS);
CREATE INDEX IDX_KYC_SUBMITTED ON KYC_DOCUMENTS(SUBMITTED_AT);



