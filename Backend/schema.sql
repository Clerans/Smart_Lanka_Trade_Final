-- 1. SL_USERS Table (Core Identity & Access Management)
CREATE TABLE SL_USERS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) UNIQUE NOT NULL,
    PASSWORD VARCHAR2(255) NOT NULL,
    ROLE VARCHAR2(20) DEFAULT 'INVESTOR' NOT NULL, -- 'INVESTOR', 'ADMIN'
    EXPO_PUSH_TOKEN VARCHAR2(255),
    IS_VERIFIED NUMBER(1) DEFAULT 0 NOT NULL,
    KYC_STATUS VARCHAR2(20) DEFAULT 'UNVERIFIED' NOT NULL, -- 'UNVERIFIED', 'PENDING', 'VERIFIED', 'REJECTED'
    FAILED_ATTEMPTS NUMBER DEFAULT 0 NOT NULL,
    ACCOUNT_LOCKED_UNTIL TIMESTAMP,
    LAST_LOGIN TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX IDX_USERS_EMAIL ON SL_USERS(EMAIL);
CREATE INDEX IDX_USERS_ROLE ON SL_USERS(ROLE);

-- 2. WALLETS Table (LKR & Foreign Currency Balances)
CREATE TABLE WALLETS (
    WALLET_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL UNIQUE,
    BALANCE_LKR NUMBER(18, 2) DEFAULT 1000000.00 NOT NULL, -- Simulated Demo LKR Balance
    USD_BALANCE NUMBER(18, 2) DEFAULT 0.00 NOT NULL,       -- Simulated USD Conversion Balance
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_WALLETS_USER FOREIGN KEY (USER_ID) REFERENCES SL_USERS(ID) ON DELETE CASCADE
);

CREATE INDEX IDX_WALLETS_USER ON WALLETS(USER_ID);

-- 3. PORTFOLIOS Table (User Holdings in CSE Equities)
CREATE TABLE PORTFOLIOS (
    PORTFOLIO_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    SYMBOL VARCHAR2(20) NOT NULL,
    QUANTITY NUMBER(18, 4) DEFAULT 0.0 NOT NULL, -- Number of shares
    AVERAGE_PRICE NUMBER(18, 2) DEFAULT 0.0 NOT NULL, -- Weighted average buy price in LKR
    INVESTED_AMOUNT NUMBER(18, 2) DEFAULT 0.0 NOT NULL, -- Total LKR invested
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_PORTFOLIOS_USER FOREIGN KEY (USER_ID) REFERENCES SL_USERS(ID) ON DELETE CASCADE,
    CONSTRAINT UQ_USER_SYMBOL UNIQUE (USER_ID, SYMBOL)
);

CREATE INDEX IDX_PORTFOLIOS_USER ON PORTFOLIOS(USER_ID);
CREATE INDEX IDX_PORTFOLIOS_SYM ON PORTFOLIOS(SYMBOL);

-- 4. TRANSACTIONS Table (Financial & Stock Execution History)
CREATE TABLE TRANSACTIONS (
    TRANSACTION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    SYMBOL VARCHAR2(20) NOT NULL, -- 'LKR', 'USD', or Stock Symbol e.g. 'JKH.N0000'
    TRANSACTION_TYPE VARCHAR2(20) NOT NULL, -- 'BUY', 'SELL', 'DEPOSIT', 'WITHDRAW', 'CONVERSION'
    QUANTITY NUMBER(18, 4) NOT NULL,
    PRICE NUMBER(18, 2) NOT NULL,
    TOTAL_AMOUNT NUMBER(18, 2) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'COMPLETED' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_TRANSACTIONS_USER FOREIGN KEY (USER_ID) REFERENCES SL_USERS(ID) ON DELETE CASCADE
);

CREATE INDEX IDX_TRANSACTIONS_USER ON TRANSACTIONS(USER_ID);
CREATE INDEX IDX_TRANSACTIONS_TYPE ON TRANSACTIONS(TRANSACTION_TYPE);

-- 5. SL_ALERTS Table (Price Monitoring & Triggers)
CREATE TABLE SL_ALERTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    SYMBOL VARCHAR2(20) NOT NULL,
    TARGET_PRICE NUMBER(20, 4) NOT NULL,
    ALERT_TYPE VARCHAR2(10) NOT NULL, -- 'ABOVE' or 'BELOW'
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL, -- 1 = active, 0 = triggered/disabled
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_USER_ALERT FOREIGN KEY (USER_ID) REFERENCES SL_USERS(ID) ON DELETE CASCADE
);

CREATE INDEX IDX_ALERTS_USER ON SL_ALERTS(USER_ID);
CREATE INDEX IDX_ALERTS_ACTIVE ON SL_ALERTS(IS_ACTIVE);

-- 6. SL_EMAIL_VERIFICATION Table (Secure Hashed OTPs)
CREATE TABLE SL_EMAIL_VERIFICATION (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    OTP_HASH VARCHAR2(255) NOT NULL,
    EXPIRES_AT TIMESTAMP NOT NULL,
    ATTEMPTS NUMBER DEFAULT 0 NOT NULL,
    VERIFIED NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_EMAIL_VER_USER FOREIGN KEY (USER_ID) REFERENCES SL_USERS(ID) ON DELETE CASCADE
);

CREATE INDEX IDX_EMAIL_VER_USER ON SL_EMAIL_VERIFICATION(USER_ID);

-- 7. SL_PASSWORD_RESET Table (Secure Hashed Password Reset OTPs)
CREATE TABLE SL_PASSWORD_RESET (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    OTP_HASH VARCHAR2(255) NOT NULL,
    EXPIRES_AT TIMESTAMP NOT NULL,
    ATTEMPTS NUMBER DEFAULT 0 NOT NULL,
    USED NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_PW_RESET_USER FOREIGN KEY (USER_ID) REFERENCES SL_USERS(ID) ON DELETE CASCADE
);

CREATE INDEX IDX_PW_RESET_USER ON SL_PASSWORD_RESET(USER_ID);

-- 8. SL_KYC_DOCUMENTS Table (OCR & Identity Verification)
CREATE TABLE SL_KYC_DOCUMENTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL UNIQUE,
    DOC_TYPE VARCHAR2(30) DEFAULT 'SRI_LANKAN_NIC' NOT NULL, -- 'SRI_LANKAN_NIC', 'PASSPORT', 'DRIVING_LICENSE'
    NIC_NUMBER VARCHAR2(50) NOT NULL,
    FULL_NAME VARCHAR2(150) NOT NULL,
    DOB VARCHAR2(30),
    GENDER VARCHAR2(10),
    STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL, -- 'PENDING', 'APPROVED', 'REJECTED'
    OCR_RAW_TEXT CLOB,
    REVIEWED_BY NUMBER,
    REVIEW_NOTES VARCHAR2(255),
    VERIFIED_AT TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_KYC_USER FOREIGN KEY (USER_ID) REFERENCES SL_USERS(ID) ON DELETE CASCADE
);

CREATE INDEX IDX_KYC_USER ON SL_KYC_DOCUMENTS(USER_ID);
CREATE INDEX IDX_KYC_STATUS ON SL_KYC_DOCUMENTS(STATUS);

-- 9. SL_AUDIT_LOGS Table (Regulatory & Security Audit Trail)
CREATE TABLE SL_AUDIT_LOGS (
    AUDIT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER,
    ACTION VARCHAR2(50) NOT NULL, -- 'LOGIN_SUCCESS', 'LOGIN_FAILED', 'TRADE_BUY', 'TRADE_SELL', 'KYC_SUBMITTED', 'KYC_APPROVED', etc.
    ENTITY VARCHAR2(50) NOT NULL, -- 'USER', 'WALLET', 'TRADE', 'KYC', 'SECURITY'
    ENTITY_ID VARCHAR2(50),
    IP_ADDRESS VARCHAR2(64),
    USER_AGENT VARCHAR2(255),
    DETAILS VARCHAR2(1000),
    STATUS VARCHAR2(20) DEFAULT 'SUCCESS' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX IDX_AUDIT_USER ON SL_AUDIT_LOGS(USER_ID);
CREATE INDEX IDX_AUDIT_ACTION ON SL_AUDIT_LOGS(ACTION);
CREATE INDEX IDX_AUDIT_DATE ON SL_AUDIT_LOGS(CREATED_AT);

-- 10. MARKET_CACHE Table (CSE Stock Prices & Market Statistics)
CREATE TABLE MARKET_CACHE (
    SYMBOL VARCHAR2(20) PRIMARY KEY,
    COMPANY_NAME VARCHAR2(100) NOT NULL,
    SECTOR VARCHAR2(50) NOT NULL,
    PRICE_LKR NUMBER(18, 2) NOT NULL,
    CHANGE_PERCENT NUMBER(8, 2) DEFAULT 0.0 NOT NULL,
    OPEN_PRICE NUMBER(18, 2) NOT NULL,
    HIGH_PRICE NUMBER(18, 2) NOT NULL,
    LOW_PRICE NUMBER(18, 2) NOT NULL,
    PREV_CLOSE NUMBER(18, 2) NOT NULL,
    VOLUME NUMBER(18, 0) DEFAULT 0 NOT NULL,
    LAST_UPDATED TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 11. CURRENCY_RATES Table (Foreign Exchange Benchmarking)
CREATE TABLE CURRENCY_RATES (
    PAIR VARCHAR2(20) PRIMARY KEY, -- e.g. 'USD/LKR', 'EUR/LKR', 'GBP/LKR', 'JPY/LKR', 'AUD/LKR'
    BASE_CURRENCY VARCHAR2(10) NOT NULL,
    TARGET_CURRENCY VARCHAR2(10) NOT NULL,
    RATE NUMBER(18, 4) NOT NULL,
    CHANGE_24H NUMBER(8, 2) DEFAULT 0.0 NOT NULL,
    LAST_UPDATED TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 12. AI_PREDICTIONS Table (ML Model Forecasts)
CREATE TABLE AI_PREDICTIONS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SYMBOL VARCHAR2(20) NOT NULL,
    MODEL_NAME VARCHAR2(50) NOT NULL, -- 'ARIMA_TIME_SERIES', 'LSTM_NEURAL_NET', 'RANDOM_FOREST'
    CURRENT_PRICE NUMBER(18, 2) NOT NULL,
    PREDICTED_PRICE NUMBER(18, 2) NOT NULL,
    DIRECTION VARCHAR2(10) NOT NULL, -- 'BULLISH', 'BEARISH', 'NEUTRAL'
    CONFIDENCE_SCORE NUMBER(5, 2) NOT NULL, -- 0.00 to 100.00
    HORIZON VARCHAR2(20) DEFAULT '24_HOURS' NOT NULL,
    SUMMARY VARCHAR2(500) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX IDX_AI_SYMBOL ON AI_PREDICTIONS(SYMBOL);

-- 13. NEWS_SENTIMENT Table (NLP Financial News Sentiment Analysis)
CREATE TABLE NEWS_SENTIMENT (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SYMBOL VARCHAR2(20) NOT NULL,
    HEADLINE VARCHAR2(255) NOT NULL,
    SOURCE VARCHAR2(100) NOT NULL,
    SENTIMENT_SCORE NUMBER(5, 2) NOT NULL, -- -1.00 to +1.00
    SENTIMENT_LABEL VARCHAR2(20) NOT NULL, -- 'BULLISH', 'BEARISH', 'NEUTRAL'
    CONFIDENCE NUMBER(5, 2) NOT NULL,
    PUBLISHED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX IDX_SENTIMENT_SYM ON NEWS_SENTIMENT(SYMBOL);
