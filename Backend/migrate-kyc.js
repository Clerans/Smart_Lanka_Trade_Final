const oracledb = require('oracledb');
require('dotenv').config({ quiet: true });

async function migrateKYC() {
  console.log('--- Oracle Database Schema Migration: KYC Documents ---');
  let connection;
  try {
    connection = await oracledb.getConnection({
      user: process.env.DB_USER,
      password: process.env.DB_PASSWORD,
      connectString: process.env.DB_CONNECT,
      configDir: process.env.DB_WALLET_PATH,
      walletLocation: process.env.DB_WALLET_PATH,
      walletPassword: process.env.DB_WALLET_PASSWORD
    });

    console.log('✅ Connected to Oracle. Updating SL_USERS and creating KYC_DOCUMENTS...');

    // 1. Add KYC_STATUS, NIC_NUMBER, ROLE to SL_USERS if not present
    const userColumns = [
      { col: 'KYC_STATUS', type: "VARCHAR2(20) DEFAULT 'NOT_SUBMITTED' NOT NULL" },
      { col: 'NIC_NUMBER', type: "VARCHAR2(50)" },
      { col: 'ROLE', type: "VARCHAR2(20) DEFAULT 'USER' NOT NULL" }
    ];

    for (const item of userColumns) {
      try {
        await connection.execute(`ALTER TABLE SL_USERS ADD ${item.col} ${item.type}`);
        console.log(`   - [SUCCESS] Added column ${item.col} to SL_USERS`);
      } catch (err) {
        if (err.message.includes('ORA-01430') || err.message.includes('already exists')) {
          console.log(`   - [SKIPPED] Column ${item.col} already exists in SL_USERS`);
        } else {
          console.warn(`   - [WARN] Column ${item.col}: ${err.message}`);
        }
      }
    }

    // 2. Create KYC_DOCUMENTS table
    try {
      await connection.execute(`
        CREATE TABLE KYC_DOCUMENTS (
          ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          USER_ID NUMBER NOT NULL,
          DOCUMENT_TYPE VARCHAR2(20) DEFAULT 'NIC' NOT NULL,
          DOCUMENT_NUMBER VARCHAR2(50),
          EXTRACTED_NAME VARCHAR2(200),
          EXTRACTED_DOB VARCHAR2(50),
          EXTRACTED_GENDER VARCHAR2(20),
          OCR_TEXT VARCHAR2(4000),
          OCR_CONFIDENCE NUMBER(5, 2),
          VERIFICATION_STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
          REJECTION_REASON VARCHAR2(500),
          DOCUMENT_PATH VARCHAR2(500),
          SUBMITTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
          VERIFIED_AT TIMESTAMP,
          VERIFIED_BY NUMBER,
          CONSTRAINT FK_KYC_DOC_USER FOREIGN KEY (USER_ID) REFERENCES SL_USERS(ID)
        )
      `);
      console.log('   - [SUCCESS] Created KYC_DOCUMENTS table');
    } catch (err) {
      if (err.message.includes('ORA-00955') || err.message.includes('already exists')) {
        console.log('   - [SKIPPED] KYC_DOCUMENTS table already exists');
      } else {
        console.error('   - [ERROR] Failed creating KYC_DOCUMENTS:', err.message);
        throw err;
      }
    }

    // Indexes
    try {
      await connection.execute(`CREATE INDEX IDX_KYC_USER ON KYC_DOCUMENTS(USER_ID)`);
      console.log('   - [SUCCESS] Created IDX_KYC_USER');
    } catch (e) {
      console.log('   - [SKIPPED] IDX_KYC_USER exists');
    }

    try {
      await connection.execute(`CREATE INDEX IDX_KYC_STATUS ON KYC_DOCUMENTS(VERIFICATION_STATUS)`);
      console.log('   - [SUCCESS] Created IDX_KYC_STATUS');
    } catch (e) {
      console.log('   - [SKIPPED] IDX_KYC_STATUS exists');
    }

    try {
      await connection.execute(`CREATE INDEX IDX_KYC_SUBMITTED ON KYC_DOCUMENTS(SUBMITTED_AT)`);
      console.log('   - [SUCCESS] Created IDX_KYC_SUBMITTED');
    } catch (e) {
      console.log('   - [SKIPPED] IDX_KYC_SUBMITTED exists');
    }

    console.log('🎉 KYC Schema migration completed successfully!');
  } catch (error) {
    console.error('❌ KYC Migration failed:', error.message);
  } finally {
    if (connection) {
      try { await connection.close(); } catch (e) {}
    }
    process.exit(0);
  }
}

migrateKYC();
