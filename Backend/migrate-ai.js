const oracledb = require('oracledb');
require('dotenv').config();

async function migrateAI() {
  console.log('--- Oracle Database Schema Migration: AI Recommendations ---');
  let connection;
  try {
    connection = await oracledb.getConnection({
      user: process.env.DB_USER,
      password: process.env.DB_PASSWORD,
      connectString: process.env.DB_CONNECT
    });

    console.log('✅ Connected to Oracle. Updating AI_RECOMMENDATIONS table...');

    try {
      await connection.execute(`DROP TABLE AI_RECOMMENDATIONS CASCADE CONSTRAINTS`);
      console.log('   - [SUCCESS] Dropped old AI_RECOMMENDATIONS table');
    } catch (e) {
      // ignore
    }

    try {
      await connection.execute(`
        CREATE TABLE AI_RECOMMENDATIONS (
          ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          USER_ID NUMBER,
          SYMBOL VARCHAR2(20) NOT NULL,
          TIMEFRAME VARCHAR2(10) DEFAULT '1h' NOT NULL,
          PRICE_USD NUMBER(18, 8) NOT NULL,
          PRICE_LKR NUMBER(18, 2) NOT NULL,
          RECOMMENDATION VARCHAR2(10) NOT NULL,
          CONFIDENCE NUMBER(5, 2) NOT NULL,
          RISK_LEVEL VARCHAR2(10) NOT NULL,
          TREND VARCHAR2(10) NOT NULL,
          RSI NUMBER(8, 2),
          SMA20 NUMBER(18, 8),
          SMA50 NUMBER(18, 8),
          EMA20 NUMBER(18, 8),
          MACD NUMBER(18, 8),
          MACD_SIGNAL NUMBER(18, 8),
          MACD_HISTOGRAM NUMBER(18, 8),
          VOLATILITY NUMBER(10, 6),
          REASONS VARCHAR2(4000),
          CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
          CONSTRAINT FK_AI_REC_USER FOREIGN KEY (USER_ID) REFERENCES SL_USERS(ID)
        )
      `);
      console.log('   - [SUCCESS] Created AI_RECOMMENDATIONS table with TIMEFRAME column');
    } catch (err) {
      console.error('   - [ERROR] Failed creating AI_RECOMMENDATIONS:', err.message);
      throw err;
    }

    // Indexes
    try {
      await connection.execute(`CREATE INDEX IDX_AI_REC_SYM ON AI_RECOMMENDATIONS(SYMBOL)`);
      console.log('   - [SUCCESS] Created IDX_AI_REC_SYM');
    } catch (err) {
      console.log('   - [SKIPPED] IDX_AI_REC_SYM exists');
    }

    try {
      await connection.execute(`CREATE INDEX IDX_AI_REC_CREATED ON AI_RECOMMENDATIONS(CREATED_AT)`);
      console.log('   - [SUCCESS] Created IDX_AI_REC_CREATED');
    } catch (err) {
      console.log('   - [SKIPPED] IDX_AI_REC_CREATED exists');
    }

    console.log('🎉 AI Recommendation schema migration completed successfully!');
  } catch (error) {
    console.error('❌ Migration failed:', error.message);
  } finally {
    if (connection) {
      try {
        await connection.close();
      } catch (e) {}
    }
    process.exit(0);
  }
}

migrateAI();
