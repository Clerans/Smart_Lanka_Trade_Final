const oracledb = require('oracledb');
require('dotenv').config();

async function runMigration() {
  let connection;

  const dbConfig = {
    user: process.env.DB_USER,
    password: process.env.DB_PASSWORD,
    connectString: process.env.DB_CONNECT
  };

  if (process.env.DB_WALLET_PATH) {
    dbConfig.configDir = process.env.DB_WALLET_PATH;
    dbConfig.walletLocation = process.env.DB_WALLET_PATH;
    if (process.env.DB_WALLET_PASSWORD) {
      dbConfig.walletPassword = process.env.DB_WALLET_PASSWORD;
    }
  }

  try {
    console.log('🔄 Connecting to Oracle Database...');
    connection = await oracledb.getConnection(dbConfig);
    console.log('✅ Connected to Oracle Database.');

    // 1. Create EMAIL_OTPS table if not exists
    console.log('🔄 Checking/Creating EMAIL_OTPS table...');
    try {
      await connection.execute(`
        CREATE TABLE EMAIL_OTPS (
            ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            EMAIL VARCHAR2(150) NOT NULL,
            OTP_HASH VARCHAR2(64) NOT NULL,
            EXPIRES_AT TIMESTAMP NOT NULL,
            ATTEMPTS NUMBER DEFAULT 0 NOT NULL,
            CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
        )
      `);
      console.log('✅ Created EMAIL_OTPS table.');
    } catch (err) {
      if (err.errorNum === 955) {
        // ORA-00955: name is already used by an existing object
        console.log('ℹ️ Table EMAIL_OTPS already exists.');
      } else {
        throw err;
      }
    }

    // 2. Create Index on EMAIL_OTPS(EMAIL)
    console.log('🔄 Checking/Creating index on EMAIL_OTPS(EMAIL)...');
    try {
      await connection.execute(`
        CREATE INDEX IDX_EMAIL_OTPS_EMAIL ON EMAIL_OTPS(EMAIL)
      `);
      console.log('✅ Created index IDX_EMAIL_OTPS_EMAIL.');
    } catch (err) {
      if (err.errorNum === 955 || err.errorNum === 1408) {
        console.log('ℹ️ Index IDX_EMAIL_OTPS_EMAIL already exists.');
      } else {
        console.warn('⚠️ Index notice:', err.message);
      }
    }

    // 3. Add EMAIL_VERIFIED column to SL_USERS if not present
    console.log('🔄 Checking/Adding EMAIL_VERIFIED column to SL_USERS...');
    try {
      await connection.execute(`
        ALTER TABLE SL_USERS ADD EMAIL_VERIFIED NUMBER(1) DEFAULT 0 NOT NULL
      `);
      console.log('✅ Added EMAIL_VERIFIED column to SL_USERS.');
    } catch (err) {
      if (err.errorNum === 1430) {
        // ORA-01430: column being added already exists in table
        console.log('ℹ️ Column EMAIL_VERIFIED already exists in SL_USERS.');
      } else {
        console.warn('⚠️ Column notice:', err.message);
      }
    }

    // Sync EMAIL_VERIFIED with IS_VERIFIED for existing verified users
    try {
      await connection.execute(`
        UPDATE SL_USERS SET EMAIL_VERIFIED = 1 WHERE IS_VERIFIED = 1 AND EMAIL_VERIFIED = 0
      `);
      await connection.commit();
      console.log('✅ Synchronized existing verified users (EMAIL_VERIFIED = 1).');
    } catch (syncErr) {
      console.warn('⚠️ Verification status sync notice:', syncErr.message);
    }

    console.log('🎉 EMAIL_OTPS migration completed successfully!');
  } catch (err) {
    console.error('❌ Migration failed:', err.message);
  } finally {
    if (connection) {
      try {
        await connection.close();
      } catch (err) {
        console.error('Error closing connection:', err);
      }
    }
  }
}

if (require.main === module) {
  runMigration();
}

module.exports = runMigration;
