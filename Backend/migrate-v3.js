const oracledb = require('oracledb');
require('dotenv').config({ quiet: true });

async function migrate() {
  console.log('--- Oracle Database Schema Migration (v3) ---');
  let connection;
  try {
    connection = await oracledb.getConnection({
      user: process.env.DB_USER,
      password: process.env.DB_PASSWORD,
      connectString: process.env.DB_CONNECT,
      configDir: process.env.DB_WALLET_PATH,
      walletLocation: process.env.DB_WALLET_PATH,
      walletPassword: process.env.DB_WALLET_PASSWORD
    });

    console.log('✅ Connected to Oracle. Creating WALLETS table...');

    // 1. Create WALLETS
    try {
      await connection.execute(`
        CREATE TABLE WALLETS (
          WALLET_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          USER_ID NUMBER NOT NULL UNIQUE,
          BALANCE_LKR NUMBER(15, 2) DEFAULT 1000000.00 NOT NULL,
          CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
          UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
          CONSTRAINT FK_WALLETS_USER FOREIGN KEY (USER_ID) REFERENCES SL_USERS(ID)
        )
      `);
      console.log('   - [SUCCESS] Created WALLETS table');
    } catch (err) {
      if (err.message.includes('ORA-00955') || err.message.includes('already exists')) {
        console.log('   - [SKIPPED] WALLETS table already exists');
      } else {
        console.error('   - [ERROR] Failed creating WALLETS:', err.message);
        throw err;
      }
    }

    // 2. Create PORTFOLIOS
    console.log('Creating PORTFOLIOS table...');
    try {
      await connection.execute(`
        CREATE TABLE PORTFOLIOS (
          PORTFOLIO_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          USER_ID NUMBER NOT NULL,
          SYMBOL VARCHAR2(20) NOT NULL,
          QUANTITY NUMBER(18, 8) DEFAULT 0.0 NOT NULL,
          AVERAGE_PRICE NUMBER(18, 2) DEFAULT 0.0 NOT NULL,
          INVESTED_AMOUNT NUMBER(18, 2) DEFAULT 0.0 NOT NULL,
          CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
          UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
          CONSTRAINT FK_PORTFOLIOS_USER FOREIGN KEY (USER_ID) REFERENCES SL_USERS(ID),
          CONSTRAINT UQ_USER_SYMBOL UNIQUE (USER_ID, SYMBOL)
        )
      `);
      console.log('   - [SUCCESS] Created PORTFOLIOS table');
    } catch (err) {
      if (err.message.includes('ORA-00955') || err.message.includes('already exists')) {
        console.log('   - [SKIPPED] PORTFOLIOS table already exists');
      } else {
        console.error('   - [ERROR] Failed creating PORTFOLIOS:', err.message);
        throw err;
      }
    }

    // 3. Create TRANSACTIONS
    console.log('Creating TRANSACTIONS table...');
    try {
      await connection.execute(`
        CREATE TABLE TRANSACTIONS (
          TRANSACTION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          USER_ID NUMBER NOT NULL,
          SYMBOL VARCHAR2(20) NOT NULL,
          TRANSACTION_TYPE VARCHAR2(15) NOT NULL, -- 'BUY', 'SELL', 'DEPOSIT', 'WITHDRAW'
          QUANTITY NUMBER(18, 8) NOT NULL,
          PRICE NUMBER(18, 2) NOT NULL,
          TOTAL_AMOUNT NUMBER(18, 2) NOT NULL,
          STATUS VARCHAR2(20) DEFAULT 'COMPLETED' NOT NULL,
          CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
          CONSTRAINT FK_TRANSACTIONS_USER FOREIGN KEY (USER_ID) REFERENCES SL_USERS(ID)
        )
      `);
      console.log('   - [SUCCESS] Created TRANSACTIONS table');
    } catch (err) {
      if (err.message.includes('ORA-00955') || err.message.includes('already exists')) {
        console.log('   - [SKIPPED] TRANSACTIONS table already exists');
      } else {
        console.error('   - [ERROR] Failed creating TRANSACTIONS:', err.message);
        throw err;
      }
    }

    // 4. Create MARKET_CACHE
    console.log('Creating MARKET_CACHE table...');
    try {
      await connection.execute(`
        CREATE TABLE MARKET_CACHE (
          SYMBOL VARCHAR2(20) PRIMARY KEY,
          PRICE_USD NUMBER(18, 8) NOT NULL,
          PRICE_LKR NUMBER(18, 2) NOT NULL,
          LAST_UPDATED TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
        )
      `);
      console.log('   - [SUCCESS] Created MARKET_CACHE table');
    } catch (err) {
      if (err.message.includes('ORA-00955') || err.message.includes('already exists')) {
        console.log('   - [SKIPPED] MARKET_CACHE table already exists');
      } else {
        console.error('   - [ERROR] Failed creating MARKET_CACHE:', err.message);
        throw err;
      }
    }

    // 5. Create indexes
    console.log('Creating indexes for demo trading...');
    const indexes = [
      { sql: `CREATE INDEX IDX_WALLETS_USER ON WALLETS(USER_ID)`, desc: 'IDX_WALLETS_USER' },
      { sql: `CREATE INDEX IDX_PORTFOLIOS_USER ON PORTFOLIOS(USER_ID)`, desc: 'IDX_PORTFOLIOS_USER' },
      { sql: `CREATE INDEX IDX_PORTFOLIOS_SYM ON PORTFOLIOS(SYMBOL)`, desc: 'IDX_PORTFOLIOS_SYM' },
      { sql: `CREATE INDEX IDX_TRANSACTIONS_USER ON TRANSACTIONS(USER_ID)`, desc: 'IDX_TRANSACTIONS_USER' }
    ];

    for (const idx of indexes) {
      try {
        await connection.execute(idx.sql);
        console.log(`   - [SUCCESS] Created index ${idx.desc}`);
      } catch (err) {
        if (err.message.includes('ORA-00955') || err.message.includes('already exists') || err.message.includes('name is already used')) {
          console.log(`   - [SKIPPED] Index ${idx.desc} already exists`);
        } else {
          console.error(`   - [ERROR] Failed creating index ${idx.desc}:`, err.message);
        }
      }
    }

    // 6. Initialize Wallets for existing users
    console.log('Populating virtual balances for existing users...');
    try {
      const result = await connection.execute(`
        INSERT INTO WALLETS (USER_ID, BALANCE_LKR)
        SELECT ID, 1000000.00 FROM SL_USERS
        WHERE ID NOT IN (SELECT USER_ID FROM WALLETS)
      `);
      console.log(`   - [SUCCESS] Initialized ${result.rowsAffected || 0} user wallets with LKR 1,000,000`);
    } catch (err) {
      console.error('   - [ERROR] Failed populating user wallets:', err.message);
      throw err;
    }

    await connection.commit();
    console.log('---------------------------------------------');
    console.log('🎉 Database Schema Migration (v3) Completed Successfully!');
  } catch (err) {
    console.error('❌ Migration Failed:', err.message);
    process.exit(1);
  } finally {
    if (connection) {
      try {
        await connection.close();
      } catch (err) {
        console.error(err);
      }
    }
  }
}

migrate();
