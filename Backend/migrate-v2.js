const oracledb = require('oracledb');
require('dotenv').config();

async function migrate() {
  console.log('--- Oracle Database Schema Migration (v2) ---');
  let connection;
  try {
    connection = await oracledb.getConnection({
      user: process.env.DB_USER,
      password: process.env.DB_PASSWORD,
      connectString: process.env.DB_CONNECT,
      configDir: process.env.DB_WALLET_PATH,
      walletLocation: process.env.DB_WALLET_PATH,
      walletPassword: process.env.DB_WALLET_PASSWORD
    });

    console.log('✅ Connected to Oracle. Altering SL_USERS table columns...');

    // Define table alterations for SL_USERS
    const alterations = [
      {
        sql: `ALTER TABLE SL_USERS ADD FAILED_ATTEMPTS NUMBER DEFAULT 0 NOT NULL`,
        desc: 'Add FAILED_ATTEMPTS to SL_USERS'
      },
      {
        sql: `ALTER TABLE SL_USERS ADD ACCOUNT_LOCKED_UNTIL TIMESTAMP`,
        desc: 'Add ACCOUNT_LOCKED_UNTIL to SL_USERS'
      },
      {
        sql: `ALTER TABLE SL_USERS ADD LAST_LOGIN TIMESTAMP`,
        desc: 'Add LAST_LOGIN to SL_USERS'
      },
      {
        sql: `ALTER TABLE SL_USERS ADD UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP`,
        desc: 'Add UPDATED_AT to SL_USERS'
      }
    ];

    for (const alt of alterations) {
      try {
        await connection.execute(alt.sql);
        console.log(`   - [SUCCESS] ${alt.desc}`);
      } catch (err) {
        if (err.message.includes('ORA-01430') || err.message.includes('already exists')) {
          console.log(`   - [SKIPPED] ${alt.desc} (already exists)`);
        } else {
          console.error(`   - [ERROR] Failed: ${alt.desc}:`, err.message);
          throw err;
        }
      }
    }

    // Define table creations
    console.log('Creating SL_PASSWORD_RESET table...');
    try {
      await connection.execute(`
        CREATE TABLE SL_PASSWORD_RESET (
          ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          USER_ID NUMBER NOT NULL,
          OTP VARCHAR2(6) NOT NULL,
          EXPIRES_AT TIMESTAMP NOT NULL,
          USED NUMBER(1) DEFAULT 0 NOT NULL,
          CONSTRAINT FK_PW_RESET_USER FOREIGN KEY (USER_ID) REFERENCES SL_USERS(ID)
        )
      `);
      console.log('   - [SUCCESS] Created SL_PASSWORD_RESET table');
    } catch (err) {
      if (err.message.includes('ORA-00955') || err.message.includes('already exists')) {
        console.log('   - [SKIPPED] SL_PASSWORD_RESET already exists');
      } else {
        console.error('   - [ERROR] Failed creating SL_PASSWORD_RESET:', err.message);
        throw err;
      }
    }

    console.log('Creating SL_EMAIL_VERIFICATION table...');
    try {
      await connection.execute(`
        CREATE TABLE SL_EMAIL_VERIFICATION (
          ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          USER_ID NUMBER NOT NULL,
          OTP VARCHAR2(6) NOT NULL,
          EXPIRES_AT TIMESTAMP NOT NULL,
          VERIFIED NUMBER(1) DEFAULT 0 NOT NULL,
          CONSTRAINT FK_EMAIL_VER_USER FOREIGN KEY (USER_ID) REFERENCES SL_USERS(ID)
        )
      `);
      console.log('   - [SUCCESS] Created SL_EMAIL_VERIFICATION table');
    } catch (err) {
      if (err.message.includes('ORA-00955') || err.message.includes('already exists')) {
        console.log('   - [SKIPPED] SL_EMAIL_VERIFICATION already exists');
      } else {
        console.error('   - [ERROR] Failed creating SL_EMAIL_VERIFICATION:', err.message);
        throw err;
      }
    }

    // Indexes
    console.log('Creating indexes...');
    const indexes = [
      { sql: `CREATE INDEX IDX_PW_RESET_USER ON SL_PASSWORD_RESET(USER_ID)`, desc: 'IDX_PW_RESET_USER' },
      { sql: `CREATE INDEX IDX_EMAIL_VER_USER ON SL_EMAIL_VERIFICATION(USER_ID)`, desc: 'IDX_EMAIL_VER_USER' }
    ];

    for (const idx of indexes) {
      try {
        await connection.execute(idx.sql);
        console.log(`   - [SUCCESS] Created index ${idx.desc}`);
      } catch (err) {
        if (err.message.includes('ORA-00955') || err.message.includes('already exists') || err.message.includes('name is already used')) {
          console.log(`   - [SKIPPED] Index ${idx.desc} already exists`);
        } else {
          console.error(`   - [ERROR] Failed creating index ${idx.desc}:`, err.message);
        }
      }
    }

    await connection.commit();
    console.log('---------------------------------------------');
    console.log('🎉 Database Schema Migration Completed Successfully!');
  } catch (err) {
    console.error('❌ Migration Failed:', err.message);
    process.exit(1);
  } finally {
    if (connection) {
      try {
        await connection.close();
      } catch (err) {
        console.error(err);
      }
    }
  }
}

migrate();
